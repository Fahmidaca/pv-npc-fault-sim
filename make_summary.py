"""Builds dataset/summary.csv (one row per run) and dataset/README.md (tables) from dataset/runs/*.npz."""
import os, csv, numpy as np
D = 'dataset'
labels = list(csv.DictReader(open(os.path.join(D, 'labels.csv'))))
rows = []
for L in labels:
    f = os.path.join(D, 'runs', f"run_{int(L['run']):03d}.npz")
    if not os.path.exists(f): continue
    z = np.load(f); X = z['data']; c = {n: k for k, n in enumerate(z['cols'])}; Tf = float(z['Tf'])
    pre, post = X[:, 0] < Tf, X[:, 0] > Tf + 0.2
    P = X[:, c['Vpv']] * X[:, c['Ipv']] / 1e3
    rms = lambda m, k: float(np.mean(np.sqrt(np.mean(X[m][:, [c[k + '_a'], c[k + '_b'], c[k + '_c']]] ** 2, 0))))
    rows.append(dict(run=L['run'], file=f"runs/run_{int(L['run']):03d}.npz", cls=f"C{int(L['cls']):02d}",
                     group=L['group'], group_name=L['group_name'], profile=L['profile'], G0=L['G0'], T=L['T'],
                     Tf=L['Tf'], params=L['params'], samples=len(X),
                     P_pre_kW=round(float(P[pre].mean()), 2), P_post_kW=round(float(P[post].mean()), 2),
                     Vdc_post=round(float(X[post, c['Vdc']].mean()), 1),
                     Iinv_rms_pre=round(rms(pre, 'Iinv'), 1), Iinv_rms_post=round(rms(post, 'Iinv'), 1),
                     Ia_mean_post=round(float(X[post, c['Iinv_a']].mean()), 1)))
with open(os.path.join(D, 'summary.csv'), 'w', newline='') as fh:
    w = csv.DictWriter(fh, rows[0].keys()); w.writeheader(); w.writerows(rows)

names = {'C00': 'Healthy', 'C13': 'Boost switch open', 'C14': 'Partial shading', 'C15': 'String open',
         'C16': 'Current-sensor gain', 'C17': 'Grid voltage sag'}
for k in range(1, 13): names[f'C{k:02d}'] = f"S{(k-1)%4+1}{'abc'[(k-1)//4]} open"
cls_tab = ['| Class | Fault | Group | Runs | P pre (kW) | P post (kW) | Iinv rms post (A) | Ia DC post (A) |',
           '|---|---|---|---|---|---|---|---|']
for cl in sorted({r['cls'] for r in rows}):
    R = [r for r in rows if r['cls'] == cl]; m = lambda k: np.mean([r[k] for r in R])
    cls_tab.append(f"| {cl} | {names[cl]} | {R[0]['group']} {R[0]['group_name']} | {len(R)} | {m('P_pre_kW'):.1f} | "
                   f"{m('P_post_kW'):.1f} | {m('Iinv_rms_post'):.1f} | {m('Ia_mean_post'):+.1f} |")
run_tab = ['| Run | Class | Group | Profile | G0 | T | Tf | Fault params | P pre | P post | File |', '|---|---|---|---|---|---|---|---|---|---|---|']
for r in rows:
    run_tab.append(f"| {r['run']} | {r['cls']} | {r['group_name']} | {r['profile']} | {r['G0']} | {r['T']} | {r['Tf']} | "
                   f"{r['params'] or '-'} | {r['P_pre_kW']} | {r['P_post_kW']} | [npz]({r['file']}) |")
size = sum(os.path.getsize(os.path.join(D, 'runs', f)) for f in os.listdir(os.path.join(D, 'runs'))) / 1e6
open(os.path.join(D, 'README.md'), 'w', encoding='utf-8').write(f"""# Dataset

{len(rows)} simulation runs (18 classes × 20 weather profiles), generated by `../make_dataset.py`. Total size {size:.0f} MB.

- `runs/run_NNN.npz`: one run each, 0.2 s before to 0.4 s after the fault, 20 kHz, float32 (`data`, `cols`, `cls`, `group`, `Tf`)
- `labels.csv`: label table (class, group, switch, weather profile, G, T, Tf, fault parameters)
- `summary.csv`: per-run features (pre/post-fault PV power, Vdc, inverter current rms, phase-a DC offset)

Weather profiles: 1–15 fixed (G = 200/400/600/800/1000 W/m² × T = 15/30/45 °C); 16 ramp down 1000→400; 17 ramp up 400→1000; 18 cloud dip 900→300→900; 19 fast drop 700→250; 20 fluctuation 600 ± 150 W/m² at 3 Hz.

## Per-class summary (mean over 20 runs)

{chr(10).join(cls_tab)}

## All runs

{chr(10).join(run_tab)}
""")
print('\n'.join(cls_tab)); print(f'{len(rows)} runs, {size:.0f} MB')
